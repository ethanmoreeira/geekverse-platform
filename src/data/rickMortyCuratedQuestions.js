/** Retorna perguntas curadas por modo. */
export const getCuratedQuestionsByMode = (mode) => {
  switch (mode) {
    case 'easy':
      return [...easyQuestions];
    case 'medium':
      return [...mediumQuestions];
    case 'hard':
      return [...hardQuestions];
    default:
      return [...easyQuestions];
  }
};

/** Retorna todas as perguntas curadas. */
export const getAllCuratedQuestions = () => [
  ...easyQuestions,
  ...mediumQuestions,
  ...hardQuestions,
];
